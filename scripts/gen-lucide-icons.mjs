#!/usr/bin/env node
// Generates CodegiOS/DesignSystem/Web/LucideIcons.generated.swift — a typed
// Swift enum of the Lucide icons the app uses, with their codepoints in the
// bundled lucide.ttf, plus the SF Symbol → Lucide translation table the port
// leans on while screens are migrated.
//
//   node scripts/gen-lucide-icons.mjs
//
// Inputs (both vendored, so this needs no network):
//   scripts/lucide-codepoints.json  — from lucide-static, name → codepoint
//   scripts/sf-to-lucide.json       — the icons we use, and the SF mapping
//
// Only the requested icons are emitted, not all 2,132: a typed enum of the set
// the app actually uses gives autocomplete and a compile error on a typo. Need a
// new icon? Add its name to `extras` in sf-to-lucide.json and re-run.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = resolve(HERE, "..")
const OUT = resolve(REPO, "CodegiOS/DesignSystem/Web/LucideIcons.generated.swift")

const codepoints = JSON.parse(
  readFileSync(resolve(HERE, "lucide-codepoints.json"), "utf8")
)
const mapping = JSON.parse(readFileSync(resolve(HERE, "sf-to-lucide.json"), "utf8"))

const sfMap = mapping.map
const requested = [
  ...new Set([...Object.values(sfMap).filter(Boolean), ...mapping.extras]),
].sort()

const unknown = requested.filter((name) => !(name in codepoints))
if (unknown.length) {
  console.error(
    `These names are not in lucide.ttf (check lucide.dev for the canonical ` +
      `spelling):\n  ${unknown.join("\n  ")}`
  )
  process.exit(1)
}

/** `folder-git-2` → `folderGit2`; `x` → `x`. */
const camel = (kebab) =>
  kebab.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())

/** Swift keywords that can't be bare enum case names. */
const RESERVED = new Set(["import", "class", "return", "default", "repeat", "case", "where", "internal", "operator", "protocol", "extension"])
const caseName = (kebab) => {
  const name = camel(kebab)
  return RESERVED.has(name) ? `\`${name}\`` : name
}

const unmapped = Object.entries(sfMap)
  .filter(([, lucide]) => lucide === null)
  .map(([sf]) => sf)

let out = `// Generated by scripts/gen-lucide-icons.mjs — DO NOT EDIT BY HAND.
//
// The Lucide icons this app uses (${requested.length} of the ${
  Object.keys(codepoints).length
} in the bundled
// lucide.ttf), addressed by codepoint. Lucide is the web client's icon library
// (\`iconLibrary: "lucide"\` in its components.json), so using the same font here
// is what keeps the two clients' glyphs identical rather than merely similar.
//
// Add an icon by listing its name in scripts/sf-to-lucide.json and re-running.

import SwiftUI

/// A Lucide glyph in the bundled icon font.
enum Lucide: String, CaseIterable, Sendable {
`

for (const name of requested) {
  out += `    case ${caseName(name)} = "${name}"\n`
}

out += `
    /// The glyph's codepoint in lucide.ttf.
    var codepoint: UInt32 {
        switch self {
`
for (const name of requested) {
  const cp = codepoints[name]
  out += `        case .${caseName(name)}: return ${cp} // U+${cp
    .toString(16)
    .toUpperCase()}\n`
}
out += `        }
    }

    /// The glyph as a one-character string, for \`Text\`.
    var glyph: String {
        guard let scalar = UnicodeScalar(codepoint) else { return "" }
        return String(Character(scalar))
    }
}

extension Lucide {
    /// The SF Symbol the app used for this concept before the port, so a call
    /// site can be migrated by name instead of by eye. Returns nil when the
    /// symbol has no Lucide counterpart and the call site needs a real decision
    /// — for example a filled status dot, which the web draws as a shape
    /// (\`WebStatusDot\`) rather than an icon.
${unmapped.length ? `    ///\n    /// Deliberately unmapped: ${unmapped.map((s) => `\`${s}\``).join(", ")}.\n` : ""}    static func forSFSymbol(_ systemName: String) -> Lucide? {
        switch systemName {
`

// Group SF symbols by target icon so the switch reads as a translation table.
const bySymbol = Object.entries(sfMap)
  .filter(([, lucide]) => lucide !== null)
  .sort(([a], [b]) => a.localeCompare(b))

for (const [sf, lucide] of bySymbol) {
  out += `        case "${sf}": return .${caseName(lucide)}\n`
}

out += `        default: return nil
        }
    }
}
`

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, out)

console.log(
  `wrote ${OUT}\n  ${requested.length} icons, ${bySymbol.length} SF Symbol mappings` +
    (unmapped.length ? `, ${unmapped.length} deliberately unmapped` : "")
)
